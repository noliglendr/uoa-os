"use client";

import { useEffect, useRef, useState } from "react";
import { useRouter } from "next/navigation";
import { createClient } from "@/lib/supabase/client";

type State =
  | { step: "loading" }
  | { step: "enroll"; factorId: string; qrCode: string; secret: string }
  | { step: "verify"; factorId: string }
  | { step: "failed"; message: string };

// Second login step. First visit: set up an authenticator app (scan a QR code).
// Later visits: enter the 6-digit code from the app.
export default function MfaPage() {
  const router = useRouter();
  const [state, setState] = useState<State>({ step: "loading" });
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [pending, setPending] = useState(false);
  const started = useRef(false);

  useEffect(() => {
    // React runs effects twice in development; enroll only once.
    if (started.current) return;
    started.current = true;

    (async () => {
      const supabase = createClient();
      const { data, error } = await supabase.auth.mfa.listFactors();
      if (error) {
        setState({ step: "failed", message: "Could not load your sign-in settings. Please sign in again." });
        return;
      }

      const verified = data.totp[0];
      if (verified) {
        setState({ step: "verify", factorId: verified.id });
        return;
      }

      // Remove setups that were started but never finished, then start a fresh one.
      for (const factor of data.all) {
        if (factor.factor_type === "totp" && factor.status === "unverified") {
          await supabase.auth.mfa.unenroll({ factorId: factor.id });
        }
      }

      const enrolled = await supabase.auth.mfa.enroll({
        factorType: "totp",
        friendlyName: "Authenticator app",
      });
      if (enrolled.error) {
        setState({ step: "failed", message: "Could not start authenticator setup. Please try again." });
        return;
      }

      setState({
        step: "enroll",
        factorId: enrolled.data.id,
        qrCode: enrolled.data.totp.qr_code,
        secret: enrolled.data.totp.secret,
      });
    })();
  }, []);

  async function onSubmit(e: React.FormEvent<HTMLFormElement>) {
    e.preventDefault();
    if (state.step !== "enroll" && state.step !== "verify") return;

    setPending(true);
    setError(null);

    const supabase = createClient();
    const { error } = await supabase.auth.mfa.challengeAndVerify({
      factorId: state.factorId,
      code: code.trim(),
    });

    if (error) {
      setError("That code did not work. Check the app and try the newest code.");
      setPending(false);
      return;
    }

    router.replace("/");
    router.refresh();
  }

  async function signOut() {
    await createClient().auth.signOut();
    router.replace("/login");
    router.refresh();
  }

  return (
    <main className="flex flex-1 items-center justify-center p-6">
      <div className="w-full max-w-sm space-y-4">
        <h1 className="text-2xl font-semibold">Two-step sign-in</h1>

        {state.step === "loading" && <p className="text-sm text-zinc-500">Loading…</p>}

        {state.step === "failed" && (
          <p role="alert" className="text-sm text-red-600">
            {state.message}
          </p>
        )}

        {state.step === "enroll" && (
          <div className="space-y-3 text-sm">
            <p>
              Scan this code with an authenticator app (for example Google Authenticator or
              Microsoft Authenticator). You only do this once.
            </p>
            {/* The QR code is an SVG data URL generated by Supabase. */}
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img src={state.qrCode} alt="QR code for your authenticator app" className="h-48 w-48 bg-white p-2" />
            <p className="text-zinc-500">
              Can&apos;t scan? Enter this key in the app:{" "}
              <code className="break-all font-mono">{state.secret}</code>
            </p>
          </div>
        )}

        {state.step === "verify" && (
          <p className="text-sm">Enter the 6-digit code from your authenticator app.</p>
        )}

        {(state.step === "enroll" || state.step === "verify") && (
          <form onSubmit={onSubmit} className="space-y-3">
            <input
              inputMode="numeric"
              autoComplete="one-time-code"
              pattern="[0-9]{6}"
              maxLength={6}
              required
              value={code}
              onChange={(e) => setCode(e.target.value)}
              aria-label="6-digit code"
              className="w-full rounded border border-zinc-300 px-3 py-2 text-center font-mono text-lg tracking-widest dark:border-zinc-700 dark:bg-zinc-900"
            />
            {error && (
              <p role="alert" className="text-sm text-red-600">
                {error}
              </p>
            )}
            <button
              type="submit"
              disabled={pending}
              className="w-full rounded bg-zinc-900 px-3 py-2 font-medium text-white disabled:opacity-50 dark:bg-zinc-100 dark:text-zinc-900"
            >
              {pending ? "Checking…" : "Continue"}
            </button>
          </form>
        )}

        <button type="button" onClick={signOut} className="text-sm text-zinc-500 underline">
          Sign out
        </button>
      </div>
    </main>
  );
}
